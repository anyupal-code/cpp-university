#include <iostream>

// Демонстрация структуры программы:
// include -> main -> вывод -> return

int main() {
    std::cout << "Структура программы:\n";
    std::cout << "1. #include <iostream>\n";
    std::cout << "2. int main()\n";
    std::cout << "3. операторы\n";
    std::cout << "4. return 0;\n";
    return 0;
}