#include <iostream>

// const и указатели: три разных комбинации.

int main() {
    int x = 5, y = 10;

    // 1. Указатель на константу
    const int* p1 = &x;
    std::cout << "*p1 = " << *p1 << "\n";
    // *p1 = 100;    // ошибка: значение менять нельзя
    p1 = &y;         // ок: сам указатель можно менять
    std::cout << "p1 теперь на y: *p1 = " << *p1 << "\n\n";

    // 2. Константный указатель
    int* const p2 = &x;
    *p2 = 100;       // ок: значение можно менять
    // p2 = &y;      // ошибка: нельзя перевести
    std::cout << "после *p2 = 100: x = " << x << "\n\n";

    // 3. Константный указатель на константу
    const int* const p3 = &y;
    std::cout << "*p3 = " << *p3 << "\n";
    // *p3 = 200;    // ошибка
    // p3 = &x;      // ошибка

    return 0;
}
